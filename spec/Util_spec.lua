local helper = require("spec.helper")
local Util = helper.load("Util").Util

describe("Util.ParseNpcID", function()
	it("reads the npcID from a creature GUID", function()
		assert.are.equal(299, Util.ParseNpcID("Creature-0-4372-0-17-299-0000123456"))
	end)
	it("works when server and spawn fields are obfuscated", function()
		assert.are.equal(6, Util.ParseNpcID("Creature-0-a1b2-0-17-6-Zx9QwE"))
	end)
	it("accepts vehicles", function()
		assert.are.equal(42, Util.ParseNpcID("Vehicle-0-1-0-1-42-00AB"))
	end)
	it("rejects players, objects and junk", function()
		assert.is_nil(Util.ParseNpcID("Player-1234-0ABCDEF0"))
		assert.is_nil(Util.ParseNpcID("GameObject-0-1-0-1-42-00AB"))
		assert.is_nil(Util.ParseNpcID(nil))
		assert.is_nil(Util.ParseNpcID("Creature-0-1"))
	end)
end)

describe("Util.FormatDuration", function()
	it("formats seconds, minutes and hours", function()
		assert.are.equal("0s", Util.FormatDuration(0))
		assert.are.equal("45s", Util.FormatDuration(45))
		assert.are.equal("2m 05s", Util.FormatDuration(125))
		assert.are.equal("1h 02m", Util.FormatDuration(3720))
	end)
	it("clamps negatives to zero", function()
		assert.are.equal("0s", Util.FormatDuration(-30))
	end)
end)

describe("Util.Distance", function()
	it("measures yards on one continent", function()
		assert.are.equal(5, Util.Distance({ c = 0, x = 0, y = 0 }, { c = 0, x = 3, y = 4 }))
	end)
	it("is nil across continents or with a missing position", function()
		assert.is_nil(Util.Distance({ c = 0, x = 0, y = 0 }, { c = 1, x = 0, y = 0 }))
		assert.is_nil(Util.Distance(nil, { c = 0, x = 0, y = 0 }))
	end)
end)

describe("Util.Median", function()
	it("handles odd, even and empty lists without reordering input", function()
		local list = { 300, 100, 200 }
		assert.are.equal(200, Util.Median(list))
		assert.are.same({ 300, 100, 200 }, list)
		assert.are.equal(150, Util.Median({ 100, 200 }))
		assert.is_nil(Util.Median({}))
	end)
end)
